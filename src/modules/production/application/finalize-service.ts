export interface FinalizeProductionOptions {
    media: Pick<MediaFactories, "createFilmAssembler">;
    seriesId: string;
    episodeNumber: number;
    script: unknown;
    bible: FinalizeServiceStore;
    outputDir?: string;
    allowMockMedia?: boolean;
    onFinalize?: (ctx: {
        seriesId: string;
        episodeNumber: number;
        script: unknown;
        bible: FinalizeServiceStore;
    }) => Promise<{
        masterVideoPath?: string;
        canonCommitted?: boolean;
        qaReport?: AssemblyQaReport;
    }>;
}
export interface FinalizeProductionResult {
    success: boolean;
    masterVideoPath?: string;
    canonCommitted?: boolean;
    commitId?: string;
    qaReport?: AssemblyQaReport;
    error?: string;
    missingApprovals?: string[];
    mockTakesDetected?: string[];
}
/**
 * Unified Finalize Service for Episodic Video Production (PR2).
 * Shared by Review Server (/api/series/finalize) and CLI (series finalize).
 *
 * Enforces:
 * 1. Completeness: every shot has an approved take whose file exists.
 * 2. Provenance Gate: reject any take generated by 'mock' provider (unless allowMockMedia is explicitly true).
 * 3. Audio Timeline Fidelity: reads timeline.json / audio.wav and supplies multi-track stems,
 *    preventing silent stems or missing soundtrack.
 * 4. QA Gate: validates manifest.qaReport.isValid === true before canon mutation.
 * 5. Lifecycle & Idempotency: requires approved lifecycle, computes deterministic commitId,
 *    and prevents duplicate commits on re-finalization.
 */
export async function finalizeProduction(options: FinalizeProductionOptions): Promise<FinalizeProductionResult> {
    const { seriesId, episodeNumber, bible } = options;
    const script = FinalizeScriptSchema.parse(options.script);
    if (!script.scenes || script.scenes.length === 0) {
        return {
            success: false,
            error: "Không thể finalize: Kịch bản không có cảnh nào (scenes rỗng).",
            missingApprovals: [],
        };
    }
    // 1. Completeness & Provenance check across all shots
    const approvedTakesMap = new Map<string, ShotTakeRecord | null>();
    const unapprovedShots: string[] = [];
    const mockTakesDetected: string[] = [];
    for (const scene of script.scenes) {
        for (const shot of scene.shots || []) {
            const approved = bible.getApprovedTakeForShot(seriesId, episodeNumber, shot.shotId);
            approvedTakesMap.set(shot.shotId, approved);
            if (!approved) {
                unapprovedShots.push(`${shot.shotId} (chưa có take được duyệt)`);
            }
            else if (!approved.local_path || !existsSync(approved.local_path)) {
                unapprovedShots.push(`${shot.shotId} (file take không tồn tại trên đĩa: ${approved.local_path || "rỗng"})`);
            }
            else if (!options.allowMockMedia) {
                if (approved.provider === "mock") {
                    mockTakesDetected.push(`${shot.shotId} (provider: mock)`);
                }
                else if (approved.qa_status === "UNAVAILABLE" || approved.qa_status === "FAIL" || approved.qa_status === "WARN") {
                    mockTakesDetected.push(`${shot.shotId} (QA status is ${approved.qa_status} - cannot commit to canon)`);
                }
                else if (approved.qa_report_json) {
                    try {
                        const parsedQa = TakeQaEvidenceSchema.parse(JSON.parse(approved.qa_report_json));
                        // isMockVector === true: explicit mock vector flag set by synthetic embedding path.
                        // status === "UNAVAILABLE" or "FAIL": no real biometric comparison or failed test.
                        // 0 frames extracted: empty or unreadable video.
                        if (parsedQa.isMockVector === true ||
                            parsedQa.status === "UNAVAILABLE" ||
                            parsedQa.qa_status === "UNAVAILABLE" ||
                            parsedQa.status === "FAIL" ||
                            parsedQa.qa_status === "FAIL" ||
                            (parsedQa.status === "WARN" && parsedQa.notes?.includes("No frames extracted"))) {
                            mockTakesDetected.push(`${shot.shotId} (mock or unverified frames detected in QA report)`);
                        }
                    }
                    catch (error) {
                        log.warn(`[FINALIZE QA] Invalid evidence for ${shot.shotId}: ${String(error)}`);
                        mockTakesDetected.push(`${shot.shotId} (QA evidence is malformed)`);
                    }
                }
            }
        }
    }
    if (unapprovedShots.length > 0) {
        return {
            success: false,
            error: `Không thể finalize: Còn ${unapprovedShots.length} shot chưa có take được duyệt (${unapprovedShots.join(", ")}).`,
            missingApprovals: unapprovedShots,
        };
    }
    if (mockTakesDetected.length > 0) {
        return {
            success: false,
            error: `[PROVENANCE GATE] Không thể commit canon với media mock. Các shot dùng mock: ${mockTakesDetected.join(", ")}. Vui lòng tạo media thật trước khi finalize.`,
            mockTakesDetected,
        };
    }
    const ledger = bible.getSeriesBudgetLedger(seriesId);
    const plan = bible.getActiveSeriesPlan(seriesId);
    const beatCoveragePassed = !plan || CoverageLedgerManager.verifyBeatCoverageInAssembly(bible, seriesId, plan.id, episodeNumber).isValid;
    const qualityBlockers = evaluateCanonGate({ mockMedia: false, mockAudio: false, mockVisualQa: false, auditPassed: true, faceWarnings: 0, faceFailures: 0, faceUnavailable: 0,
        unapprovedShots: unapprovedShots.length, beatCoveragePassed, billingUncertain: ledger.uncertainAttemptCount > 0, budgetExceeded: ledger.totalCommittedUsd > ledger.maxBudgetUsd });
    if (qualityBlockers.length)
        return { success: false, error: qualityBlockers.join(', ') };
    try {
        assertDirectorLifecycle(bible.getEpisodeLifecycle(seriesId, episodeNumber));
    }
    catch (error) {
        return { success: false, error: '[LIFECYCLE GATE] ' + String(error), canonCommitted: false };
    }
    // A custom renderer must return verified output; approval remains an application gate.
    // Custom renderer hook
    if (options.onFinalize) {
        const res = await options.onFinalize({
            seriesId,
            episodeNumber,
            script,
            bible,
        });
        if (!res.masterVideoPath || !existsSync(res.masterVideoPath) || res.qaReport?.isValid !== true)
            return { success: false, error: 'FINALIZATION_QA_REQUIRED', canonCommitted: false };
        return completeFinalization(options, script, res.masterVideoPath, res.qaReport);
    }
    // 2. Build assembly inputs
    const scenesInput: SceneAssemblyInput[] = (script.scenes || []).map((sc, scIdx) => ({
        sceneNumber: sc.sceneNumber ?? scIdx + 1,
        sceneId: sc.sceneId || `scene_${scIdx + 1}`,
        shots: (sc.shots || []).map((sh) => {
            const approved = approvedTakesMap.get(sh.shotId);
            return {
                shotId: sh.shotId,
                sceneId: sc.sceneId || `scene_${scIdx + 1}`,
                takeId: approved?.id || `take_${sh.shotId}`,
                sourceClipPath: approved?.local_path || "",
                rawDurationSec: sh.durationSec,
                trimStartSec: sh.trimStartSec ?? 0,
                trimEndSec: sh.trimEndSec,
                transitionIn: sh.transitionIn,
                transitionOut: sh.transitionOut,
                isApproved: Boolean(approved ? approved.is_approved : false),
            };
        }),
    }));
    const epNumStr = String(episodeNumber).padStart(2, "0");
    const baseEpDir = options.outputDir
        ? options.outputDir
        : join("output", "series", seriesId, `ep-${epNumStr}`);
    const assemblyOutputDir = join(baseEpDir, "assembly");
    // 3. Load Audio Cues and Timeline if available to prevent silent stem output
    let dialogueCues: TimelineDialogueCue[] | undefined;
    let sfxCues: TimelineSfxCue[] | undefined;
    let ambienceCues: TimelineAmbienceCue[] | undefined;
    let bgmTrack: TimelineBgmCue | undefined;
    let subtitleCues: TimelineSubtitleCue[] | undefined;
    const timelinePath = join(baseEpDir, "timeline.json");
    if (existsSync(timelinePath)) {
        try {
            const rawTl = await readFile(timelinePath, "utf8");
            const tl = decodeFinalizationTimeline(JSON.parse(rawTl),script.fps||30);
            dialogueCues = tl.dialogueTrack;
            // Fix: avoid short-circuiting on empty array — an empty sfxTrack should
            // still fall through to sfxTracks if that has actual content.
            sfxCues =
                Array.isArray(tl.sfxTrack) && tl.sfxTrack.length > 0
                    ? tl.sfxTrack
                    : tl.sfxTracks ?? tl.sfxTrack;
            // Normalize: timeline.json may store ambienceTrack as a single object
            // instead of an array. Wrap it so hierarchicalAssembler.assemble() can
            // always call .map() on the array.
            const rawAmbience = Array.isArray(tl.ambienceTrack)
                ? tl.ambienceTrack
                : tl.ambienceTrack != null
                    ? [tl.ambienceTrack]
                    : [];
            // Warn and filter out any ambience entries missing audioPath — they would
            // silently produce a silent audio stem in the assembler.
            const filteredAmbience = rawAmbience.filter((a) => {
                if (!a.audioPath) {
                    log.warn(`[FINALIZE SERVICE] Bỏ qua ambience cue '${a.name || a.cueId || "unknown"}': thiếu trường audioPath. Cue này sẽ không được render thành audio.`);
                    return false;
                }
                return true;
            });
            ambienceCues = filteredAmbience.length > 0 ? filteredAmbience : undefined;
            bgmTrack = tl.bgmTrack;
            subtitleCues = tl.subtitleTrack || tl.subtitleCues;
        }
        catch (err: unknown) {
            log.warn(`[FINALIZE SERVICE] Không thể nạp timeline.json: ${String(err)}`);
            return { success: false, error: "TIMELINE_INVALID", canonCommitted: false };
        }
    }
    const effectiveAspect = (script.aspectRatio || "9:16") as "9:16" | "16:9" | "1:1";
    const dims = resolveVideoDimensions(effectiveAspect, (options as any).exportResolution);
    const hierarchicalAssembler = options.media.createFilmAssembler({
        seriesId,
        episodeNumber,
        title: script.title,
        fps: script.fps || 30,
        aspectRatio: effectiveAspect,
        width: dims.width,
        height: dims.height,
        scenes: scenesInput,
        dialogueCues,
        sfxCues,
        ambienceCues,
        bgmTrack,
        subtitleCues,
        outputDir: assemblyOutputDir,
        requireApprovedShots: true,
    });
    const manifest = await hierarchicalAssembler.assemble();
    let masterPath = manifest.masterOutputs.masterVideoPath;
    if (!masterPath || !existsSync(masterPath)) {
        throw new Error(`[FINALIZATION GATE] Master video không tồn tại sau khi assemble: ${masterPath || "null"}`);
    }
    // 4. Ensure master video has combined audio if assembler did not produce a master audio stem
    const hasAssembledAudio = Boolean(manifest.masterOutputs?.masterAudioPath) &&
        existsSync(manifest.masterOutputs.masterAudioPath);
    if (!hasAssembledAudio) {
        const candidateAudioWav = join(baseEpDir, "audio.wav");
        const candidateAudioMp3 = join(baseEpDir, "audio", "master-soundtrack.mp3");
        const candidateAudio = existsSync(candidateAudioMp3)
            ? candidateAudioMp3
            : existsSync(candidateAudioWav)
                ? candidateAudioWav
                : null;
        if (candidateAudio) {
            try {
                if (await isFfmpegAvailable()) {
                    const remuxedMaster = join(assemblyOutputDir, "master_with_audio.mp4");
                    await runFfmpeg([
                        "-y",
                        "-i",
                        masterPath,
                        "-i",
                        candidateAudio,
                        "-map",
                        "0:v:0",
                        "-map",
                        "1:a:0",
                        "-c:v",
                        "copy",
                        "-c:a",
                        "aac",
                        "-b:a",
                        "192k",
                        remuxedMaster,
                    ]);
                    if (existsSync(remuxedMaster)) {
                        masterPath = remuxedMaster;
                    }
                }
            }
            catch (muxErr: unknown) {
                log.warn(`[FINALIZE SERVICE] Audio muxing warning: ${String(muxErr)}`);
            }
        }
    }
    // Master QA passes through the same evidence gate as automated production.
    const assemblyBlockers = evaluateCanonGate({ mockMedia: false, mockAudio: false, mockVisualQa: false, auditPassed: manifest.qaReport?.isValid === true, faceWarnings: 0, faceFailures: 0, faceUnavailable: 0, unapprovedShots: 0, beatCoveragePassed, billingUncertain: ledger.uncertainAttemptCount > 0, budgetExceeded: ledger.totalCommittedUsd > ledger.maxBudgetUsd });
    if (assemblyBlockers.length) {
        const qaErrors = manifest.qaReport?.errors?.join("; ") || "QA report isValid is false";
        return {
            success: false,
            masterVideoPath: masterPath,
            qaReport: manifest.qaReport,
            error: `[FINALIZATION QA GATE] Master video không đạt tiêu chuẩn chất lượng: ${qaErrors}. Hủy bỏ commit canon.`,
        };
    }
    return completeFinalization(options, script, masterPath, manifest.qaReport);
}
function completeFinalization(options: FinalizeProductionOptions, script: z.infer<typeof FinalizeScriptSchema>, masterPath: string, qaReport: AssemblyQaReport): FinalizeProductionResult {
    const { bible, seriesId, episodeNumber } = options;
    // 6. Multi-dimensional Narrative Delta Extraction & Deterministic Canon Commit
    const delta = extractNarrativeDeltaFromScript(script, bible, seriesId);
    const charactersAppeared = new Set<string>();
    for (const scene of script.scenes || []) {
        for (const char of scene.charactersPresent || []) {
            const charId = typeof char === "string" ? char : char?.characterId;
            if (charId)
                charactersAppeared.add(charId);
        }
    }
    const summaryRecord: EpisodeSummaryRecord = {
        series_id: seriesId,
        episode_number: episodeNumber,
        title: script.title ?? `Episode ${episodeNumber}`,
        logline: script.logline ?? "",
        major_events: delta.major_events || [
            script.logline || `Hoàn thành tập ${episodeNumber}`,
        ],
        delta_changes: {
            master_video_path: masterPath,
            locations_visited: delta.world_state_updates?.locations_visited || [],
            characters_appeared: Array.from(charactersAppeared),
            wardrobe_changes: delta.character_wardrobe_updates || [],
            props_used: delta.world_state_updates?.props_active || [],
        },
        created_at: new Date().toISOString(),
    };
    // Transition lifecycle to approved by director prior to canon commit.
    // Only promotable statuses (pre-commit states) may advance to 'approved'.
    // Rejected or failed episodes must be explicitly reset by a human before re-finalization.
    // 'approved' is included to allow idempotent retry of a finalization that failed after
    // lifecycle was set but before commitEpisode completed (e.g. transient remux failure).
    // We skip the setEpisodeLifecycle write when already 'approved' to avoid a redundant
    // write and to reduce the concurrent-re-finalization race window.
    try {
        approveEpisodeForCanon(bible, seriesId, episodeNumber, 'director');
    }
    catch (error) {
        return { success: false, error: '[LIFECYCLE GATE] ' + String(error) };
    }
    const commitResult = commitEpisodeCanon(bible, summaryRecord, delta, 'director');
    // Advance coverage ledger stage to "assembled" for all shots/scenes in this episode
    try {
        const episodeLedgers = bible.listCoverageLedgers(seriesId).filter((l) => l.series_id === seriesId && l.episode_number === episodeNumber);
        for (const ledger of episodeLedgers) {
            if (ledger.adaptation_decision !== "omitted") {
                bible.upsertCoverageLedger({
                    ...ledger,
                    stage: "assembled",
                });
            }
        }
    }
    catch (covErr: unknown) {
        log.warn(`[FINALIZE SERVICE] Không thể cập nhật coverage stage sang assembled: ${String(covErr)}`);
    }
    return {
        success: true,
        masterVideoPath: masterPath,
        canonCommitted: commitResult.applied,
        commitId: commitResult.commitId,
        qaReport: qaReport,
    };
}
